tc("breadcrumb(['Home', 'Shop', 'Tea'])", "Home > Shop > Tea", breadcrumb(["Home", "Shop", "Tea"]))
tc("breadcrumb(['Home']) -- one part, no separator", "Home", breadcrumb(["Home"]))
tc("breadcrumb(['A', 'B'])", "A > B", breadcrumb(["A", "B"]))
tc("breadcrumb([]) -- no parts", "", breadcrumb([]))
